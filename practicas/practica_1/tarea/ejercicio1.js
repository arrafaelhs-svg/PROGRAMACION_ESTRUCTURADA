

// Declaramos las variables del radio y el valor de PI
let radio = 5;
let pi = 3.14159;

// Calculamos el perímetro del círculo
let perimetro = 2 * pi * radio;

// Calculamos el área del círculo
let area = pi * radio ** 2;

// Mostramos los resultados en consola
console.log(`Radio: ${radio}`);
console.log(`Perímetro: ${perimetro.toFixed(2)}`);
console.log(`Área: ${area.toFixed(2)}`);