
// Declaramos la cantidad de dólares
let dolares = 100;

// Convertimos los dólares a euros
let euros = dolares * 0.92;

// Convertimos los dólares a pesos salvadoreños
let pesosSalvadorenos = dolares * 8.75;

// Convertimos los dólares a quetzales guatemaltecos
let quetzales = dolares * 7.80;

// Mostramos las conversiones en consola
console.log(`${dolares} USD = ${euros.toFixed(2)} EUR`);
console.log(`${dolares} USD = ${pesosSalvadorenos.toFixed(2)} SVC`);
console.log(`${dolares} USD = ${quetzales.toFixed(2)} GTQ`);